"""Generate discovery files from the one inventory. Python 3.10+, stdlib only."""
from pathlib import Path
import argparse
import json
import re

ROOT = Path(__file__).resolve().parents[1]


def metadata(path):
    """Read this project's deliberately small scalar YAML frontmatter subset."""
    text = path.read_text(encoding="utf-8")
    match = re.match(r"\A---\n(.*?)\n---\n", text, re.S)
    if not match:
        raise ValueError(f"{path}: missing frontmatter")
    fields = {}
    for line in match[1].splitlines():
        key, sep, value = line.partition(":")
        if not sep or key in fields or key not in {"name", "description"}:
            raise ValueError(f"{path}: unsupported or duplicate field: {line}")
        value = value.strip()
        if key == "description" and not value.startswith('"'):
            raise ValueError(f"{path}: this project requires a quoted scalar description")
        fields[key] = json.loads(value) if value.startswith('"') else value
    if set(fields) != {"name", "description"} or not all(
        isinstance(v, str) and v.strip() for v in fields.values()
    ):
        raise ValueError(f"{path}: name and description must be nonempty strings")
    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", fields["name"]):
        raise ValueError(f"{path}: invalid skill name")
    return fields


def entries(root=ROOT):
    return json.loads((root / "catalog.json").read_text(encoding="utf-8"))["skills"]


def generated(root=ROOT):
    skills = entries(root)
    rows = ["# Skill catalog", "", "Generated by `python scripts/catalog.py --write`; edit the inventory and skill frontmatter.", "",
            f"{len(skills)} packages: {sum(s['kind'] == 'task' for s in skills)} task, "
            f"{sum(s['kind'] == 'domain' for s in skills)} domain, "
            f"{sum(s['kind'] == 'strategy' for s in skills)} strategy. These are reusable skills, not running agents.", "",
            "| Skill | Kind | When to use |", "| --- | --- | --- |"]
    manifest = {"schema_version": 2, "format": "mbse-skills-adaptation-index", "skills": []}
    result = {}
    for item in skills:
        meta = metadata(root / item["path"] / "SKILL.md")
        if item["name"] != meta["name"]:
            raise ValueError(f"Catalog/frontmatter mismatch: {item['name']}")
        rows.append(f"| [{meta['name']}](../{item['path']}/SKILL.md) | {item['kind']} | {meta['description']} |")
        manifest["skills"].append({**meta, "source_file": item["path"] + "/SKILL.md"})
        ui = {"display_name": item["display_name"], "short_description": item["short_description"], "default_prompt": item["default_prompt"]}
        result[item["path"] + "/agents/openai.yaml"] = "interface:\n" + "".join(
            f"  {k}: {json.dumps(v, ensure_ascii=False)}\n" for k, v in ui.items()
        )
    result["docs/skills.md"] = "\n".join(rows) + "\n"
    result["platform/chatgpt/gpt-manifest.json"] = json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="Regenerate derived files")
    args = parser.parse_args()
    stale = []
    for relative, value in generated().items():
        path = ROOT / relative
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(value, encoding="utf-8", newline="\n")
        elif not path.exists() or path.read_text(encoding="utf-8") != value:
            stale.append(relative)
    if stale:
        parser.exit(1, "Stale generated files: " + ", ".join(stale) + "\n")
    print("Discovery files generated" if args.write else "Discovery files current")


if __name__ == "__main__":
    main()
